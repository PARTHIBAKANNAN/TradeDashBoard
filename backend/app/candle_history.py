async def get_historical_slot_stats(
    before_date: Any, lookback_days: int = 20
) -> Dict[Tuple[str, int], dict]:
    """For every (symbol, bucket_minute) pair, the average volume + average turnover
    over that symbol's last `lookback_days` distinct trading dates strictly before `before_date`."""
    b_date = str(before_date)
    try:
        conn = _get_connection()
        cursor = conn.cursor()
        cursor.execute(
            """
            WITH recent_dates AS (
                SELECT symbol, bucket_date,
                       ROW_NUMBER() OVER (PARTITION BY symbol ORDER BY bucket_date DESC) AS rn
                FROM (SELECT DISTINCT symbol, bucket_date FROM candle_history WHERE bucket_date < ?) d
            )
            SELECT c.symbol, c.bucket_minute,
                   AVG(c.volume) AS avg_volume,
                   AVG(c.close * c.volume) AS avg_turnover,
                   COUNT(*) AS days
            FROM candle_history c
            JOIN recent_dates rd ON rd.symbol = c.symbol AND rd.bucket_date = c.bucket_date
            WHERE rd.rn <= ?
            GROUP BY c.symbol, c.bucket_minute
            """,
            (b_date, lookback_days),
        )
        rows = cursor.fetchall()
        conn.close()
        return {
            (r["symbol"], int(r["bucket_minute"])): {
                "avg_volume": float(r["avg_volume"] or 0.0),
                "avg_turnover": float(r["avg_turnover"] or 0.0),
                "days": int(r["days"]),
            }
            for r in rows
        }
    except Exception as e:
        logger.warning("get_historical_slot_stats failed: %s", e)
        return {}


async def get_startup_snapshot() -> Dict[str, dict]:
    """For every symbol, the two most recent DISTINCT trading dates on record
    with each date's high/low/last close, used to backfill state on startup."""
    try:
        conn = _get_connection()
        cursor = conn.cursor()
        cursor.execute("""
            WITH ranked_dates AS (
                SELECT symbol, bucket_date,
                       ROW_NUMBER() OVER (PARTITION BY symbol ORDER BY bucket_date DESC) AS rn
                FROM (SELECT DISTINCT symbol, bucket_date FROM candle_history) d
            ),
            day_stats AS (
                SELECT symbol, bucket_date,
                       MAX(high) AS high,
                       MIN(low) AS low
                FROM candle_history
                GROUP BY symbol, bucket_date
            ),
            latest_candles AS (
                SELECT symbol, bucket_date, close,
                       ROW_NUMBER() OVER (PARTITION BY symbol, bucket_date ORDER BY bucket_minute DESC) AS c_rn
                FROM candle_history
            )
            SELECT rd.symbol, rd.rn, rd.bucket_date, ds.high, ds.low, lc.close
            FROM ranked_dates rd
            JOIN day_stats ds ON ds.symbol = rd.symbol AND ds.bucket_date = rd.bucket_date
            JOIN latest_candles lc ON lc.symbol = rd.symbol AND lc.bucket_date = rd.bucket_date AND lc.c_rn = 1
            WHERE rd.rn <= 2
            """)
        rows = cursor.fetchall()
        conn.close()
        out: Dict[str, dict] = {}
        for r in rows:
            entry = out.setdefault(r["symbol"], {})
            prefix = "d0" if r["rn"] == 1 else "d1"
            b_date_val = r["bucket_date"]
            if isinstance(b_date_val, str) and "-" in b_date_val:
                try:
                    b_date_val = date.fromisoformat(b_date_val)
                except Exception:
                    pass
            entry[f"{prefix}_date"] = b_date_val
            entry[f"{prefix}_high"] = float(r["high"]) if r["high"] is not None else None
            entry[f"{prefix}_low"] = float(r["low"]) if r["low"] is not None else None
            entry[f"{prefix}_close"] = float(r["close"]) if r["close"] is not None else None
        return out
    except Exception as e:
        logger.warning("get_startup_snapshot failed: %s", e)
        return {}


async def seed_missing_state(market_state) -> None:
    """Called once at backend startup, and again daily at 08:45 IST (before
    market open). Backfills last known display values from local candle_history."""
    from .calculations import pct_change as _pct_change
    from .config import IST

    snapshot = await get_startup_snapshot()
    if not snapshot:
        return
    today = datetime.now(IST).date()
    with market_state.lock():
        for sym, snap in snapshot.items():
            stock = market_state.stocks.get(sym)
            if not stock:
                continue
            if snap.get("d0_date") == today:
                y_high, y_low, y_close = (
                    snap.get("d1_high"),
                    snap.get("d1_low"),
                    snap.get("d1_close"),
                )
            else:
                y_high, y_low, y_close = (
                    snap.get("d0_high"),
                    snap.get("d0_low"),
                    snap.get("d0_close"),
                )
                if not stock["ltp"] and snap.get("d0_close"):
                    stock["ltp"] = snap["d0_close"]
                if not stock["prev_close"] and snap.get("d1_close"):
                    stock["prev_close"] = snap["d1_close"]
                    stock["pct_change"] = _pct_change(stock["ltp"], stock["prev_close"])
            if not stock["yesterday_high"] and y_high:
                stock["yesterday_high"] = y_high
            if not stock["yesterday_low"] and y_low:
                stock["yesterday_low"] = y_low
            if not stock["prev_close"] and y_close:
                stock["prev_close"] = y_close
